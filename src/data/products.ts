export type Product = {
  id: number;
  name: string;
  tamil: string;
  rate: number;
  unit: string;
  price: number;
  slug: string;
  image: string | null;
};

export type Category = {
  name: string;
  products: Product[];
};

export const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

let counter = 0;
const p = (
  name: string,
  tamil: string,
  rate: number,
  unit: string,
  price = Math.round(rate * 0.1),
  image: string | null = null,
): Product => {
  counter += 1;
  return {
    id: counter,
    name,
    tamil,
    rate,
    unit,
    price,
    slug: slugify(name),
    image,
  };
};

